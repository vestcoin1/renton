let seedIndex = 0;
function build(s: Seed): Property {
  const i = seedIndex++;
  const premium = s.rent >= 8_000_000;
  return {
    description: DESCRIPTIONS[s.type],
    state: stateForCity(s.city) ?? "",
    serviceCharge: Math.round((s.rent * (premium ? 0.15 : 0.08)) / 50_000) * 50_000,
    cautionDeposit: Math.round((s.rent * 0.1) / 50_000) * 50_000,
    toilets: s.bathrooms + (s.bedrooms > 1 ? 1 : 0),
    sizeSqm: 28 + s.bedrooms * 42 + (premium ? 60 : 0),
    furnished: premium,
    parkingSpaces: s.type === "Self Contain" ? 0 : s.bedrooms >= 3 ? 3 : 1,
    waterSupply: premium ? "Borehole + Treatment" : "Borehole",
    power: premium ? "24/7 Estate Power" : s.rent > 3_000_000 ? "Prepaid + Inverter" : "Prepaid Meter",
    security: s.type !== "Self Contain" || s.rent > 1_000_000,
    amenities: premium
      ? ["24/7 Security", "Borehole", "Fitted Kitchen", "Air Conditioning", "Swimming Pool", "Gym", "Inverter Backup", "CCTV", "Parking", "Gated Estate", "Water Heater", "Wi-Fi Ready"]
      : s.rent > 2_500_000
        ? ["24/7 Security", "Borehole", "Fitted Kitchen", "Wardrobes", "Prepaid Meter", "Parking", "Gated Estate", "POP Ceiling", "Balcony"]
        : ["Borehole", "Prepaid Meter", "Wardrobes", "POP Ceiling", "Parking"],
    images: galleryFor(i),
    verification: "published",
    occupancy: "vacant",
    availableFrom: daysAgo(3),
    listedAt: daysAgo(4 + ((i * 7) % 40)),
    views: 120 + ((i * 397) % 2400),
    nearby: NEARBY[s.city] ?? [],
    verifiedAt: daysAgo(5 + ((i * 5) % 30)),
    ...s,
  };
}

